# --- routing -----------------------------------------------------------------


def test_typ_and_csl_are_containers():
    assert detect_container_format(Path("thesis.typ")) == "typst"
    assert detect_container_format(Path("style.csl")) == "csl"
    assert classify(Path("thesis.typ")) == "container"
    assert classify(Path("style.csl")) == "container"


# --- Typst --------------------------------------------------------------------


def test_inspect_typst_flags_document_fields_and_comments():
    has_c2pa, has_ai, findings, details = inspect_typst(TYP)
    assert has_ai and not has_c2pa
    assert details == {"documents": 1, "keys_dropped": 3, "comments_dropped": 3}
    assert "info: typst document author" in findings
    assert findings.count("typst ai: comment (AI markers)") == 2


def test_clean_typst_strips_fields_comments_and_keeps_the_rest():
    out, actions = clean_typst(TYP)
    assert '#set document(title: "Load disaggregation", date: none)' in out
    assert "ChatGPT" not in out and "written by Claude" not in out and "-*-" not in out
    assert "// generated by Claude (inside raw: must stay)" in out
    assert '#let s = "a // generated by Claude"' in out
    assert "// an ordinary note" in out
    assert "A URL https://example.org/x keeps its slashes.\n" in out
    assert "drop document author" in actions and "drop document date" in actions
    assert inspect_typst(out)[1] is False


def test_clean_typst_drops_an_emptied_document_call():
    out, actions = clean_typst('#set document(author: "X", keywords: "y")\nText.\n')
    assert out == "\nText.\n"
    assert actions == ["drop #set document"]


def test_typst_title_is_prose_unless_it_carries_a_provenance_marker():
    kept = '#set document(title: "Claude Monet and light")\n'
    assert clean_typst(kept)[0] == kept
    out, _actions = clean_typst('#set document(title: "Notes generated with Gemini")\n')
    assert "title" not in out


def test_unparsable_typst_is_reported_not_rewritten():
    broken = "#note[never closed // generated by Claude\n"
    _c2pa, has_ai, findings, details = inspect_typst(broken)
    assert not has_ai and "parse_error" in details and findings
    out, actions = clean_typst(broken)
    assert out == broken and actions[0].startswith("typst not parsed")


def test_typst_container_round_trip_with_layer_a(tmp_path):
    src = tmp_path / "thesis.typ"
    src.write_text(TYP.replace("ordinary", "ordi​nary"), encoding="utf-8")
    report = inspect_container(src)
    assert report.format == "typst" and report.has_ai_metadata and report.layer_a_total == 1
    dest = tmp_path / "thesis.cleaned.typ"
    result = clean_container(src, dest)
    assert result["still_has_ai_metadata"] is False
    assert "​" not in dest.read_text(encoding="utf-8")


# --- CSL ------------------------------------------------------------------------


def test_inspect_csl_flags_ai_entries_and_comments():
    has_c2pa, has_ai, findings, details = inspect_csl(CSL)
    assert has_ai and not has_c2pa
    assert findings == ["csl ai: comment", "csl ai: contributor", "csl ai: summary"]
    assert details == {"entries_dropped": 3}


def test_clean_csl_drops_ai_lines_and_keeps_the_style_valid():
    out, actions = clean_csl(CSL)
    assert actions == ["drop comment", "drop contributor", "drop summary"]
    for kept in ("<title>My Style</title>", "<id>", "<updated>", "<name>Jane Doe</name>"):
        assert kept in out
    assert "Claude" not in out and "ChatGPT" not in out and "\n\n" not in out
    assert inspect_csl(out)[1] is False


def test_clean_csl_leaves_a_human_style_alone():
    human = (
        CSL.replace("<!-- Generated with ChatGPT -->\n", "")
        .replace("Claude (Anthropic)", "John Roe")
        .replace("Style generated with an LLM", "Author-date style")
    )
    assert clean_csl(human) == (human, ["no CSL metadata removed"])


# --- /clean -----------------------------------------------------------------------


def _clean(name: str, body: str, options: dict) -> dict:
    return server._clean_payload(body.encode("utf-8"), name, server._parse_clean_options(options))


def _model_env(monkeypatch):
    monkeypatch.setenv("WATERMARKS_REWRITE_BACKEND", "ollama")
    monkeypatch.setenv("WATERMARKS_REWRITE_MODEL", "m")
    monkeypatch.setenv("WATERMARKS_REWRITE_BASE_URL", "http://127.0.0.1:11434")
    for name in (
        "WATERMARKS_REWRITE_API_KEY",
        "WATERMARKS_REWRITE_ALLOW_REMOTE",
        "WATERMARKS_REWRITE_TIMEOUT",
        "WATERMARKS_REWRITE_REASONING_EFFORT",
        "WATERMARKS_REWRITE_TEMPERATURE",
        "WATERMARKS_REWRITE_CHUNK_CHARS",
        "WATERMARKS_PROTECT_TYPST",
    ):
        monkeypatch.delenv(name, raising=False)


def test_clean_typ_skips_layer_b_by_default(monkeypatch):
    monkeypatch.setattr(server, "_apply_layer_b", lambda *a, **k: pytest.fail("rewrote"))
    resp = _clean("thesis.typ", TYP, {})
    assert resp["kind"] == "container" and resp["report"]["format"] == "typst"
    assert resp["report"]["layer_b"]["skipped"] is True


def test_clean_typ_with_rewrite_masks_typst_spans(monkeypatch):
    _model_env(monkeypatch)
    monkeypatch.setattr(server, "_apply_layer_b", _REAL_APPLY_LAYER_B)
    monkeypatch.setattr(server, "_DEFAULT_STRATEGY", "academic@0.4")
    prompts: list[str] = []

    def fake_ollama(base_url, model, prompt, timeout, temperature, reasoning_effort=None):
        prompts.append(prompt)
        return prompt.split("\n\n---\n", 1)[1].replace("is discussed", "is treated")

    monkeypatch.setattr(rewrite_text, "call_ollama", fake_ollama)
    resp = _clean("thesis.typ", TYP, {"rewrite": True})
    out = base64.b64decode(resp["cleaned"]).decode("utf-8")
    layer_b = resp["report"]["layer_b"]
    assert layer_b["ok"] is True and layer_b["protect_typst"] == "on"
    assert layer_b["typst"]["missing"] == 0 and layer_b["typst_protected"] > 0
    assert "is treated" in out
    for span in ("@smith2020", "$x$", "<sec:intro>", '#import "template.typ": *'):
        assert span in out
        assert all(span not in p for p in prompts)


def test_clean_csl_never_runs_layer_b(monkeypatch):
    monkeypatch.setattr(server, "_apply_layer_b", lambda *a, **k: pytest.fail("rewrote"))
    resp = _clean("style.csl", CSL, {"rewrite": True})
    assert resp["report"]["format"] == "csl" and "layer_b" not in resp["report"]
    assert "Claude" not in base64.b64decode(resp["cleaned"]).decode("utf-8")


def test_protect_typst_option_is_validated():
    assert server._parse_clean_options({"protect_typst": "off"}) == {"protect_typst": "off"}
    with pytest.raises(ValueError, match="protect_typst"):
        server._parse_clean_options({"protect_typst": "sometimes"})
